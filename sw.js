// Service worker: precaches the app shell + data, caches map tiles (cache-first) for offline use.
const VERSION = 'v1.1.0';
const APP_CACHE = `app-${VERSION}`;
const TILE_CACHE = 'tiles-v1';
const APP_FILES = [
  './',
  'index.html',
  'manifest.webmanifest',
  'css/app.css',
  'js/app.js',
  'js/geo.js',
  'js/hours.js',
  'vendor/leaflet/leaflet.js',
  'vendor/leaflet/leaflet.css',
  'vendor/leaflet/images/layers.png',
  'vendor/leaflet/images/layers-2x.png',
  'vendor/leaflet/images/marker-icon.png',
  'vendor/leaflet/images/marker-icon-2x.png',
  'vendor/leaflet/images/marker-shadow.png',
  'data/routes.geojson',
  'data/pois.json',
  'data/plan.json',
  'data/protected.geojson',
  'icons/icon.svg',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/icon-maskable-512.png',
];
const TILE_HOSTS = ['tile.opentopomap.org', 'tile.openstreetmap.org'];
// 1×1 transparent PNG for tiles that are neither cached nor reachable
const EMPTY_TILE = Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNkYAAAAAYAAjCB0C8AAAAASUVORK5CYII='), (c) => c.charCodeAt(0));

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const c = await caches.open(APP_CACHE);
    await c.addAll(APP_FILES.map((u) => new Request(u, { cache: 'reload' })));
    // GPX files are listed in gpx/manifest.json (generated by scripts/build-gpx.mjs)
    try {
      const res = await fetch('gpx/manifest.json', { cache: 'reload' });
      await c.put('gpx/manifest.json', res.clone());
      const list = await res.json();
      await c.addAll(list.map((g) => new Request(g.file, { cache: 'reload' })));
    } catch (e) { console.warn('GPX precache failed', e); }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('app-') && k !== APP_CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  if (TILE_HOSTS.includes(url.hostname)) {
    event.respondWith(tile(req));
    return;
  }
  if (url.origin === self.location.origin) {
    event.respondWith(appFile(req));
  }
});

async function tile(req) {
  const cache = await caches.open(TILE_CACHE);
  const hit = await cache.match(req.url);
  if (hit) return hit;
  try {
    const res = await fetch(req.url, { mode: 'cors' });
    if (res.ok) cache.put(req.url, res.clone());
    return res;
  } catch {
    return new Response(EMPTY_TILE, { headers: { 'Content-Type': 'image/png' } });
  }
}

// cache-first for the app shell; falls back to network and refreshes the cache in the background
async function appFile(req) {
  const cache = await caches.open(APP_CACHE);
  const hit = await cache.match(req, { ignoreSearch: true });
  const net = fetch(req).then((res) => {
    if (res.ok && res.type === 'basic') cache.put(req, res.clone());
    return res;
  }).catch(() => null);
  if (hit) return hit;
  const res = await net;
  if (res) return res;
  if (req.mode === 'navigate') return (await cache.match('index.html')) || Response.error();
  return Response.error();
}
